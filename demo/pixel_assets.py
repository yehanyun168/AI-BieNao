def parse_runs(text):
    """把 "x,y,w x,y,w ..." 字符串解析成 [(x, y, w), ...]"""
    out = []
    for tok in text.split():
        a, b, c = tok.split(',')
        out.append((int(a), int(b), int(c)))
    return tuple(out)


def parse_all(table):
    """{code: "x,y,w ..."} -> {code: ((x,y,w), ...)}"""
    return {k: parse_runs(v) for k, v in table.items()}


