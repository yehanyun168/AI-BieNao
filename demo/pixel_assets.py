def owner_at(gx, gy):
    """网格坐标 -> 国家代码；不在任何游戏国家内返回 None"""
    if not (0 <= gx < GRID_W and 0 <= gy < GRID_H):
        return None
    i = ord(OWNER[gy][gx]) - ord('A')
    return OWNER_CODES[i] if 0 <= i < len(OWNER_CODES) else None


